export function verifySecurityAnswer(questionIndex: number, userAnswer: string): boolean {
  if (questionIndex < 0 || questionIndex >= securityQuestions.length || !userAnswer) {
    return false;
  }

  const correctAnswer = securityQuestions[questionIndex].answer.toLowerCase().trim();
  const normalized = userAnswer.toLowerCase().trim();

  if (normalized === correctAnswer) return true;
  if (alternativeAnswers[correctAnswer]?.includes(normalized)) return true;
  if (!Number.isNaN(Number(correctAnswer)) && !Number.isNaN(Number(normalized))) {
    return Number(correctAnswer) === Number(normalized);
  }
  return false;
}
